def login_required(view):
    @functools.wraps(view)
    def wrapped_view(**kwargs):
        if not session.get('logged_in'):
            return redirect(url_for('login'))
        return view(**kwargs)
    return wrapped_view

@app.route("/")
def index():
    if not session.get('logged_in'):
        return render_template('index.html')
    else:
        return redirect(url_for('notes'))


@app.route("/notes/", methods=('GET', 'POST'))
@login_required
def notes():
    importerror=""
    noteerror=""
    #Posting a new note:
    if request.method == 'POST':
        if request.form['submit_button'] == 'add note':
            note = request.form['noteinput']

            if not note.strip(): #rejects empty notes
                noteerror = "Note cannot be empty!"
            elif len(note) > 300:  # reject long notes
                noteerror = "Note cannot be more than 300 characters!"
            else:  # save valid note
                with DatabaseConnection(app) as db:
                    statement = """INSERT INTO notes(assocUser,dateWritten,note,publicID) VALUES(?,?,?,?);"""
                    db.execute(statement, (session['userid'], time.strftime('%Y-%m-%d %H:%M:%S'), note, random.randrange(1000000000, 9999999999)))
        elif request.form['submit_button'] == 'import note':
            noteid = request.form['noteid']
            if noteid.isdigit() and len(noteid) == 10:
                with DatabaseConnection(app) as db:
                    statement = """SELECT * from NOTES where publicID = ?;"""
                    db.execute(statement, (noteid,))
                    result = db.fetchall()
                    if(len(result)>0):
                        row = result[0]
                        statement = """INSERT INTO notes(id,assocUser,dateWritten,note,publicID) VALUES(null,?,?,?,?);"""
                        db.execute(statement, (session['userid'],row[2],row[3],row[4]))
                    else:
                        importerror="No such note with that ID!"
            else:
                importerror = "Note ID must contain exactly 10 digits!"

    with DatabaseConnection(app) as db:
        statement = "SELECT * FROM notes WHERE assocUser = ?"
        db.execute(statement, (session['userid'],))
        notes = db.fetchall()
    
    return render_template('notes.html',notes=notes,importerror=importerror, noteerror=noteerror)


@app.route("/login/", methods=('GET', 'POST'))
@limiter.limit("5 per minute", error_message = "Too many login attempts. Please try again in a minute.")
def login():
    error = ""
    if request.method == 'POST':
        username = request.form['username']
        password = request.form['password']
        with DatabaseConnection(app) as db:
            statement = "SELECT * FROM users WHERE username = ?;"
            db.execute(statement, (username,))
            result = db.fetchall()

            if len(result) > 0:
                hashed_password = result[0][2]
                is_correct = check_password_hash(hashed_password, password)
                if is_correct:
                    session.clear()
                    session['logged_in'] = True
                    session['userid'] = result[0][0]
                    session['username']=result[0][1]
                    return redirect(url_for('index'))
            else:
                error = "Wrong username or password!"

    return render_template('login.html',error=error)


